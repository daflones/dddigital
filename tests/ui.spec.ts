import { test, expect } from '@playwright/test'

test('classroom preview, channel chat, notes and friends work without credentials', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/?demo=1')
  await expect(page.getByRole('heading', { name: 'Grandes ideias merecem um espaço à altura.' })).toBeVisible()
  await expect(page.getByText('MODO DEMONSTRAÇÃO')).toBeVisible()
  await page.getByRole('textbox', { name: 'Mensagem', exact: true }).fill('Minha dúvida sobre o projeto')
  await page.getByRole('button', { name: 'Enviar mensagem', exact: true }).click()
  await expect(page.getByText('Minha dúvida sobre o projeto', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Notas', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'O conhecimento fica.' })).toBeVisible()
  await page.getByRole('button', { name: 'Editar anotações' }).click()
  await page.getByRole('textbox', { name: 'Anotações compartilhadas' }).fill('# Aula de hoje\n\nVamos construir um SaaS.')
  await page.getByRole('button', { name: 'Salvar para a turma' }).click()
  await expect(page.getByRole('heading', { name: 'Aula de hoje' })).toBeVisible()
  await page.getByRole('button', { name: 'geral', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Esse é o começo de #geral' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Mensagem', exact: true }).fill('Olá, comunidade!')
  await page.getByRole('textbox', { name: 'Mensagem', exact: true }).press('Enter')
  await expect(page.getByText('Olá, comunidade!', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Amigos', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Seu círculo de builders.' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Adicionar amigo' })).toBeVisible()
  expect(errors).toEqual([])
})

test('mobile classroom stays in viewport and exposes navigation and chat', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?demo=1')
  await expect(page.getByRole('button', { name: 'Entrar na sala', exact: true })).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
  await page.getByRole('button', { name: 'Abrir chat da sala' }).click()
  await expect(page.getByRole('textbox', { name: 'Mensagem', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Fechar painel' }).click()
  await page.getByRole('button', { name: 'Abrir canais' }).click()
  await page.getByRole('button', { name: 'geral', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Esse é o começo de #geral' })).toBeVisible()
})

test('authentication and signup preserve invitations', async ({ page }) => {
  await page.goto('/?invite=dd000000-0000-4000-8000-000000000099')
  await expect(page.getByRole('heading', { name: 'Bom ter você de volta.' })).toBeVisible()
  // The fake invite id should surface the invite flow: either the server card or a friendly error.
  await expect(page.getByText(/convid|convite/i)).toBeVisible()
  await expect(page.getByText('direto no servidor', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Cadastre-se', exact: true }).click()
  await expect(page.getByLabel('Seu nome')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continuar com Google' })).toBeEnabled()
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.getByRole('button', { name: 'Esqueci minha senha' }).click()
  await expect(page.getByRole('button', { name: 'Enviar link de recuperação' })).toBeVisible()
})
